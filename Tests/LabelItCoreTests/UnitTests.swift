@Suite struct FilenameTests {
    let builder: FilenameBuilder = {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "Europe/Lisbon")!
        return FilenameBuilder(calendar: calendar)
    }()
    let date = ISO8601DateFormatter().date(from: "2026-11-02T18:41:07Z")!

    @Test func screenshotHasTime() {
        let base = builder.baseName(slug: "stripe-pricing", kind: .ui, source: .screenshot, date: date, place: nil)
        #expect(base == "stripe-pricing_2026-11-02_184107")
    }

    @Test func phoneHasPlace() {
        let base = builder.baseName(slug: "dog-beach", kind: .photo, source: .phone, date: date, place: "Lisbon")
        #expect(base == "dog-beach_lisbon_2026-11-02")
        let noPlace = builder.baseName(slug: "", kind: .photo, source: .phone, date: date, place: nil)
        #expect(noPlace == "photo_2026-11-02")
    }

    @Test func collisions() throws {
        let dir = try TempDir()
        FileManager.default.createFile(atPath: dir.url.appendingPathComponent("a.png").path, contents: Data())
        let next = builder.availableURL(in: dir.url, base: "a", ext: "PNG")
        #expect(next.lastPathComponent == "a-2.png")
        let reserved = builder.availableURL(in: dir.url, base: "a", ext: "png", reserved: [next.path])
        #expect(reserved.lastPathComponent == "a-3.png")
    }
}

