/// A temporary directory removed when the value goes away.
final class TempDir {
    let url: URL
    init() throws {
        url = FileManager.default.temporaryDirectory.appendingPathComponent("labelit-tests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
    }
    deinit { try? FileManager.default.removeItem(at: url) }
}

@Suite struct WatchFolderTests {
    @Test func addingFoldersKeepsTheListSensible() throws {
        let dir = try TempDir()
        let home = dir.url
        let fileManager = FileManager.default
        for path in ["Downloads/Phone/2026/March", "Desktop", "Pictures", "Documents/Scans", "Library/Caches", "Photos.photoslibrary"] {
            try fileManager.createDirectory(at: home.appendingPathComponent(path), withIntermediateDirectories: true)
        }
        fileManager.createFile(atPath: home.appendingPathComponent("notes.txt").path, contents: Data())
        let defaults = WatchFolders.defaults(home: home)
        func folder(_ path: String) -> URL { home.appendingPathComponent(path) }
        func reasons(_ path: String) -> WatchFolders.Rejection? {
            WatchFolders.adding([folder(path)], to: defaults, home: home).rejected.first?.reason
        }

        // A new folder is added; one deep inside Downloads too (two levels down is all Downloads covers).
        let added = WatchFolders.adding([folder("Documents/Scans"), folder("Downloads/Phone/2026/March")], to: defaults, home: home)
        #expect(added.rejected.isEmpty)
        #expect(added.folders.map(\.lastPathComponent) == ["Downloads", "Desktop", "Pictures", "Scans", "March"])

        #expect(reasons("Downloads") == .alreadyWatched)
        #expect(reasons("Downloads/Phone/2026") == .coveredBy("Downloads"))
        #expect(reasons("") == .tooBroad)
        #expect(reasons("Library/Caches") == .tooBroad)
        #expect(reasons("Photos.photoslibrary") == .package)
        #expect(reasons("notes.txt") == .notAFolder)

        // A parent replaces the folders it now covers.
        let parent = WatchFolders.adding([folder("Documents")], to: added.folders, home: home)
        #expect(parent.folders.map(\.lastPathComponent) == ["Downloads", "Desktop", "Pictures", "March", "Documents"])
    }
}

