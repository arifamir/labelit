import Foundation

public struct LabelerSettings: Sendable, Equatable {
    public var screenshots: Bool = true
    public var phone: Bool = true
    public var placeNames: Bool = false
    public var finderTags: Bool = true
    /// Use the `PhotoDescriber` (EmbeddingGemma 2) for camera photos and videos, when one is set.
    public var describePhotos: Bool = true
    /// Files created longer ago than this are left alone by the watchers (they're not "new").
    public var recentWindow: TimeInterval = 15 * 60

    public init(screenshots: Bool = true, phone: Bool = true, placeNames: Bool = false, finderTags: Bool = true,
                describePhotos: Bool = true) {
        self.screenshots = screenshots
        self.phone = phone
        self.placeNames = placeNames
        self.finderTags = finderTags
        self.describePhotos = describePhotos
    }
}

/// A rename LabelIt would make. Produced by `plan`, carried out by `apply`.
public struct Proposal: Sendable, Identifiable, Equatable {
    public var id: String { moves[0].from }
    public var source: Source
    public var kind: FileKind
    public var namer: NamerKind
    public var moves: [FileMove]
    public var context: CaptureContext?
    public var whereFroms: [String]

    public var originalName: String { (moves[0].from as NSString).lastPathComponent }
    public var newName: String { (moves[0].to as NSString).lastPathComponent }
}

/// Names that cameras, phones and screenshot tools give files. Only these get renamed,
/// so a file someone named on purpose ("Contract-signed.jpg") is never touched.
public enum NamePatterns {
    static let autoPrefixes = try! NSRegularExpression(
        pattern: #"^(img|img_e|dsc|dscn|dscf|pxl|mvimg|vid|mov|rpreplay|photo|image|untitled|screenshot|screen shot|screen recording|simulator screenshot|fullsizerender|live photo|whatsapp image|whatsapp video|pic|picture|camera|snapshot|capture|bildschirmfoto|capture d.écran|captura de pantalla|schermata|скриншот)(?![a-z])"#,
        options: [.caseInsensitive])
    /// Numbers only, a UUID (with or without dashes, as apps name the videos they save), or a long random token with
    /// letters and digits mixed. Words, even with numbers in them ("invoice2026", "report2026final"), don't match.
    static let numericOrID = try! NSRegularExpression(
        pattern: #"^[\d_\-\s.]+$|^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|^(?=[0-9a-f]*\d)(?=[0-9a-f]*[a-f])[0-9a-f]{16,}$|^(?=.*\d)(?=.*[a-z])[a-z0-9]{20,}$"#,
        options: [.caseInsensitive])

    /// macOS screenshot names carry the date and time in every language ("Screenshot 2026-11-08 at 10.41.07",
    /// "Bildschirmfoto 2026-11-08 um 10.41.07", "スクリーンショット 2026-11-08 10.41.07"). A screenshot someone
    /// renamed has lost them.
    static let screenshotTimestamp = try! NSRegularExpression(
        pattern: #"\d{4}-\d{2}-\d{2}\D{1,8}\d{1,2}[.:]\d{2}[.:]\d{2}"#)

    /// What screenshot tools call their files, in the languages GNOME, KDE and Windows ship
    /// ("Screenshot From 2026-11-08 10-41-07.png", "Screenshot_20261108_104107.png", "Bildschirmfoto vom …").
    static let screenshotWords = try! NSRegularExpression(
        pattern: #"^(screenshot|screen shot|bildschirmfoto|capture d.écran|captura de pantalla|captura de tela|schermata|schermafbeelding|skärmavbild|skjermbilde|zrzut ekranu|snímek obrazovky|képernyőkép|снимок экрана|скриншот|στιγμιότυπο|ekran görüntüsü|スクリーンショット|截屏|截图|螢幕擷取畫面|스크린샷)"#,
        options: [.caseInsensitive])

    /// Named like a screenshot tool's own file (used where the system doesn't mark screenshots, unlike macOS).
    public static func looksLikeScreenshotToolName(_ fileName: String) -> Bool {
        let stem = (fileName as NSString).deletingPathExtension
        return screenshotWords.firstMatch(in: stem, range: NSRange(stem.startIndex..., in: stem)) != nil
    }

    public static func looksLikeScreenshotName(_ fileName: String) -> Bool {
        let stem = (fileName as NSString).deletingPathExtension
        return looksAutoGenerated(fileName)
            || screenshotTimestamp.firstMatch(in: stem, range: NSRange(stem.startIndex..., in: stem)) != nil
    }

    public static func looksAutoGenerated(_ fileName: String) -> Bool {
        let stem = (fileName as NSString).deletingPathExtension
        let range = NSRange(stem.startIndex..., in: stem)
        return autoPrefixes.firstMatch(in: stem, range: range) != nil
            || numericOrID.firstMatch(in: stem, range: range) != nil
    }
}

/// The pipeline: decide whether a file is LabelIt's business, understand it, name it, rename it.
public actor Labeler {
    public typealias ContextProvider = @Sendable () async -> CaptureContext?

    private let reader: any MediaReader
    private let understanding: any ImageUnderstanding
    private var describer: (any PhotoDescriber)?
    private let namer: any Namer
    private let log: RenameLog
    private let places: (any PlaceLookup)?
    private let builder = FilenameBuilder()
    private var settings: LabelerSettings
    private var inFlight: Set<String> = []
    /// "directory/IMG_1234" → new base name, so a Live Photo's video that arrives after
    /// its image was renamed gets the same name.
    private var liveStems: [String: (base: String, expires: Date)] = [:]

    /// `LabelItPlatform`'s `Labeler.native(…)` fills these in for the platform it runs on.
    public init(reader: any MediaReader,
                understanding: any ImageUnderstanding,
                describer: (any PhotoDescriber)? = nil,
                namer: any Namer = RuleNamer(),
                log: RenameLog,
                places: (any PlaceLookup)? = nil,
                settings: LabelerSettings = LabelerSettings()) {
        self.reader = reader
        self.understanding = understanding
        self.describer = describer
        self.namer = namer
        self.log = log
        self.places = places
        self.settings = settings
    }

    public func update(settings: LabelerSettings) { self.settings = settings }

    /// Sets (or removes, with nil) the photo describer, e.g. once EmbeddingGemma 2 is downloaded.
    public func update(describer: (any PhotoDescriber)?) { self.describer = describer }

    // MARK: Entry points

    /// A file appeared in a watched folder. Renames it if it's a new screenshot or phone file.
    @discardableResult
    public func handleNewFile(_ url: URL, context: ContextProvider? = nil) async -> RenameEntry? {
        guard let source = await classify(url, requireRecent: true) else { return nil }
        guard begin(url) else { return nil }
        defer { end(url) }
        var capturedContext: CaptureContext?
        // The app in front is only meaningful for a screenshot taken seconds ago.
        if source == .screenshot, let context, let age = Self.age(of: url), age < 20 {
            capturedContext = await context()
        }
        guard let proposal = await plan(url, source: source, context: capturedContext) else { return nil }
        return try? await apply(proposal)
    }

    /// A capture from LabelIt's own hotkey: name it and move it into `directory`.
    public func labelCapture(_ tempURL: URL, context: CaptureContext?, into directory: URL) async throws -> RenameEntry {
        guard let proposal = await plan(tempURL, source: .capture, context: context, destination: directory) else {
            throw CocoaError(.fileNoSuchFile)
        }
        return try await apply(proposal)
    }

    /// Finds earlier phone files in `directory` that still have camera names, without renaming anything.
    public func planPastFiles(in directory: URL, limit: Int = 500,
                              progress: (@Sendable (Int, Int) -> Void)? = nil) async -> [Proposal] {
        let fileManager = FileManager.default
        let keys: [URLResourceKey] = [.isRegularFileKey, .creationDateKey]
        guard let contents = try? fileManager.contentsOfDirectory(
            at: directory, includingPropertiesForKeys: keys, options: [.skipsHiddenFiles]) else { return [] }
        var phoneFiles: [URL] = []
        for url in contents where await classify(url, requireRecent: false) == .phone { phoneFiles.append(url) }
        let candidates = phoneFiles
            .sorted { (Self.creationDate($0) ?? .distantPast) > (Self.creationDate($1) ?? .distantPast) }
            .prefix(limit)
        var proposals: [Proposal] = []
        var reserved: Set<String> = []
        for (index, url) in candidates.enumerated() {
            progress?(index, candidates.count)
            if var proposal = await plan(url, source: .phone, context: nil, reserved: reserved) {
                // Videos that pair with an image are handled with the image.
                proposal.moves.removeAll { move in proposals.contains { $0.moves.contains { $0.from == move.from } } }
                guard !proposal.moves.isEmpty else { continue }
                proposal.moves.forEach { reserved.insert($0.to) }
                proposals.append(proposal)
            }
        }
        progress?(candidates.count, candidates.count)
        return proposals
    }

    /// Files someone picked in Finder (right-click → Rename with LabelIt). They asked, so the watchers' rules
    /// (new, camera-style name, not renamed before) don't apply: any image or video is renamed.
    /// Returns what was renamed; files that are gone or aren't pictures are skipped.
    public func renameChosen(_ urls: [URL]) async -> [RenameEntry] {
        // Images first, so a Live Photo's video goes with its image when both are picked.
        let ordered = urls.sorted { !reader.isVideo($0) && reader.isVideo($1) }
        var entries: [RenameEntry] = []
        for url in ordered {
            // Gone: renamed along with an earlier pick (the video of a Live Photo).
            guard FileManager.default.fileExists(atPath: url.path), let source = await chosenSource(url) else { continue }
            guard begin(url) else { continue }
            defer { end(url) }
            guard let proposal = await plan(url, source: source, context: nil),
                  let entry = try? await apply(proposal) else { continue }
            entries.append(entry)
        }
        return entries
    }

    /// Where a picked file came from, when it can be told; `.finder` otherwise. Nil for anything that isn't a picture.
    func chosenSource(_ url: URL) async -> Source? {
        guard reader.isMedia(url) || reader.isDocument(url),
              let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .isPackageKey]),
              values.isRegularFile == true, values.isPackage != true else { return nil }
        if reader.isSystemScreenshot(url) { return .screenshot }
        if FileMarkers.isAirDrop(url) { return .phone }
        if reader.isImage(url), await reader.metadata(of: url).isFromAppleMobileDevice { return .phone }
        return .finder
    }

    // MARK: Deciding

    /// Returns the source if LabelIt should handle this file, or nil to leave it alone.
    public func classify(_ url: URL, requireRecent: Bool) async -> Source? {
        let name = url.lastPathComponent
        guard !name.hasPrefix("."), reader.isMedia(url) else { return nil }
        guard let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .isPackageKey]),
              values.isRegularFile == true, values.isPackage != true else { return nil }
        guard !FileMarkers.isProcessed(url) else { return nil }
        if requireRecent {
            guard let age = Self.age(of: url), age < settings.recentWindow else { return nil }
        }
        if reader.isSystemScreenshot(url) {
            // Renamed by hand (or by another screenshot tool) before LabelIt got to it: leave it.
            return settings.screenshots && NamePatterns.looksLikeScreenshotName(name) ? .screenshot : nil
        }
        guard settings.phone, NamePatterns.looksAutoGenerated(name) else { return nil }
        // The video half of a Live Photo whose image was just renamed (Image Capture copies it second).
        if reader.isVideo(url), let known = liveStems[Self.stemKey(url)], known.expires > Date() { return .phone }
        if FileMarkers.isAirDrop(url) { return .phone }
        let metadata = reader.isImage(url) ? await reader.metadata(of: url) : MediaMetadata()
        if metadata.isFromAppleMobileDevice { return .phone }
        // An iPhone screenshot that arrived without AirDrop's record (other computers, other apps): iOS marks it itself.
        if metadata.isScreenshot && !FileMarkers.isMacScreenshot(url) { return .phone }
        // Videos from an iPhone: trust the camera-style name only alongside a phone image.
        if reader.isVideo(url), Self.siblingImage(of: url) != nil { return .phone }
        return nil
    }

    // MARK: Planning

    public func plan(_ url: URL, source: Source, context: CaptureContext?, destination: URL? = nil,
                     reserved: Set<String> = []) async -> Proposal? {
        let directory = destination ?? url.deletingLastPathComponent()
        let isVideo = reader.isVideo(url)
        let isDocument = reader.isDocument(url)
        let stemKey = Self.stemKey(url)

        // The video half of a Live Photo follows its image.
        if isVideo && source == .phone {
            if let known = liveStems[stemKey], known.expires > Date() {
                let target = builder.availableURL(in: directory, base: known.base, ext: url.pathExtension, reserved: reserved)
                return Proposal(source: source, kind: .video, namer: .rules,
                                moves: [FileMove(from: url.path, to: target.path)], context: nil, whereFroms: [])
            }
            if Self.siblingImage(of: url) != nil { return nil }
        }

        let facts = await gatherFacts(url, source: source, isVideo: isVideo, isDocument: isDocument, context: context)
        let result = await namer.name(facts)
        let base = builder.baseName(slug: result.slug, kind: result.kind, source: source,
                                    date: facts.bestDate, place: facts.place)
        let target = builder.availableURL(in: directory, base: base, ext: url.pathExtension, reserved: reserved)
        var moves = [FileMove(from: url.path, to: target.path)]

        if !isVideo, source == .phone, let video = Self.siblingVideo(of: url), !FileMarkers.isProcessed(video),
           Self.arrivedTogether(url, video) {
            // One name free for both, so the pair still matches (Photos pairs a Live Photo by name).
            let shared = builder.availableBase(in: directory, base: base, exts: [url.pathExtension, video.pathExtension],
                                               reserved: reserved)
            moves = [FileMove(from: url.path, to: FilenameBuilder.url(in: directory, base: shared, ext: url.pathExtension).path),
                     FileMove(from: video.path, to: FilenameBuilder.url(in: directory, base: shared, ext: video.pathExtension).path)]
        }

        return Proposal(source: source, kind: result.kind, namer: result.namer, moves: moves,
                        context: facts.context, whereFroms: whereFroms(for: facts))
    }

    private func gatherFacts(_ url: URL, source: Source, isVideo: Bool, isDocument: Bool,
                             context: CaptureContext?) async -> FileFacts {
        let metadata = await reader.metadata(of: url)
        let isScreen = isDocument || FileFacts.isScreen(source: source, metadata: metadata, url: url)
        // Screens and pages need resolution for small text; photos don't.
        let image = await reader.picture(of: url, maxPixelSize: isVideo ? 1280 : isScreen ? 3000 : 1600)
        var analysis = if let image { await understanding.analyze(image, readText: true) } else { ImageAnalysis() }
        analysis.lines = KnownWords.correct(analysis.lines)
        // Camera photos and videos: ask the describer what the picture shows, even when it's full of text: that tells
        // a photographed letter (named from its text) from a TV's label (a photo of a thing). Not for screens.
        if !isScreen, settings.describePhotos, let describer, let image {
            let matches = await describer.describe(image)
            analysis.descriptions = PhotoWords.choose(matches, analysis: analysis, metadata: metadata)
            analysis.alternatives = PhotoWords.alternatives(matches, chosen: analysis.descriptions, analysis: analysis)
        }
        var place: String?
        if settings.placeNames, [.phone, .finder].contains(source), let lat = metadata.latitude, let lon = metadata.longitude {
            place = await places?.place(latitude: lat, longitude: lon)
        }
        // A macOS screenshot's context is read when the file lands, by then maybe from another window: it's kept only
        // when the picture shows that window's title. (⌘⇧1 reads it before the crosshair, so it's kept as read.)
        var context = context
        if source == .screenshot, let read = context, !read.isShown(in: analysis) { context = nil }
        return FileFacts(url: url, source: source, isVideo: isVideo, isDocument: isDocument, metadata: metadata, analysis: analysis,
                         context: context, place: place, fileDate: Self.creationDate(url) ?? Date())
    }

    private func whereFroms(for facts: FileFacts) -> [String] {
        var values: [String] = []
        if let context = facts.context {
            if let url = context.url { values.append(url) }
            let app = context.appName ?? ""
            let title = context.windowTitle ?? ""
            let line = [app, title].filter { !$0.isEmpty }.joined(separator: " — ")
            if !line.isEmpty { values.append(line) }
        }
        if facts.source == .phone {
            let device = facts.metadata.model ?? "iPhone"
            values.append(FileMarkers.isAirDrop(facts.url) ? "AirDrop from \(device)" : device)
        }
        return values
    }

    // MARK: Applying

    /// Renames the files, then writes the marker, Finder tags and "where from", and logs the rename.
    @discardableResult
    public func apply(_ proposal: Proposal) async throws -> RenameEntry {
        let fileManager = FileManager.default
        var moves = proposal.moves
        // Re-check for files that appeared since planning, keeping a pair on one shared name.
        let taken = moves.contains { $0.to != $0.from && fileManager.fileExists(atPath: $0.to) }
        if taken, let first = moves.first {
            let firstTarget = URL(fileURLWithPath: first.to)
            let directory = firstTarget.deletingLastPathComponent()
            let base = builder.availableBase(in: directory, base: firstTarget.deletingPathExtension().lastPathComponent,
                                             exts: moves.map { URL(fileURLWithPath: $0.to).pathExtension })
            moves = moves.map { move in
                let ext = URL(fileURLWithPath: move.to).pathExtension
                return FileMove(from: move.from, to: FilenameBuilder.url(in: directory, base: base, ext: ext).path)
            }
        }
        var done: [FileMove] = []
        for move in moves {
            let from = URL(fileURLWithPath: move.from)
            guard fileManager.fileExists(atPath: move.from) else { continue }
            let target = URL(fileURLWithPath: move.to)
            // Mark first: attributes travel with the file, so the watcher ignores the renamed copy.
            FileMarkers.markProcessed(from)
            do {
                if target.path != from.path { try fileManager.moveItem(at: from, to: target) }
            } catch {
                if done.isEmpty {
                    if proposal.source != .capture { FileMarkers.unmarkProcessed(from) }
                    throw error
                }
                continue
            }
            done.append(FileMove(from: move.from, to: target.path).identified())
            decorate(target, proposal: proposal)
        }
        guard let first = done.first else { throw CocoaError(.fileNoSuchFile) }

        if proposal.source == .phone, done.count == 1, !reader.isVideo(URL(fileURLWithPath: first.from)) {
            let base = URL(fileURLWithPath: first.to).deletingPathExtension().lastPathComponent
            liveStems[Self.stemKey(URL(fileURLWithPath: first.from))] = (base, Date().addingTimeInterval(180))
        }

        let entry = RenameEntry(source: proposal.source, kind: proposal.kind, namer: proposal.namer,
                                moves: done, context: proposal.context)
        await log.record(entry)
        return entry
    }

    private func decorate(_ url: URL, proposal: Proposal) {
        if settings.finderTags { FileMarkers.addFinderTags([proposal.kind.tagName], at: url) }
        if !proposal.whereFroms.isEmpty && FileMarkers.whereFroms(url).isEmpty {
            FileMarkers.setWhereFroms(proposal.whereFroms, at: url)
        }
        let info: [String: String] = [
            "kind": proposal.kind.rawValue,
            "source": proposal.source.rawValue,
            "namer": proposal.namer.rawValue,
            "app": proposal.context?.appName ?? "",
            "window": proposal.context?.windowTitle ?? "",
            "url": proposal.context?.url ?? "",
            "originalName": proposal.originalName,
        ].filter { !$0.value.isEmpty }
        if let data = try? JSONSerialization.data(withJSONObject: info, options: [.sortedKeys]) {
            ExtendedAttributes.set(FileMarkers.info, data: data, at: url)
        }
    }

    // MARK: Helpers

    private func begin(_ url: URL) -> Bool { inFlight.insert(url.path).inserted }
    private func end(_ url: URL) { inFlight.remove(url.path) }

    static func creationDate(_ url: URL) -> Date? { FileDates.created(atPath: url.path) }

    /// How long ago the file arrived (not when it was made: an AirDropped photo is "made" when it was taken).
    static func age(of url: URL) -> TimeInterval? {
        FileDates.arrived(atPath: url.path).map { Date().timeIntervalSince($0) }
    }

    /// An image and video with the same name are a Live Photo only if they arrived together, not an old
    /// IMG_1234.MOV that happens to share a new IMG_1234.HEIC's number.
    static func arrivedTogether(_ a: URL, _ b: URL) -> Bool {
        guard let first = FileDates.arrived(atPath: a.path), let second = FileDates.arrived(atPath: b.path) else { return false }
        return abs(first.timeIntervalSince(second)) < 10 * 60
    }

    static func stemKey(_ url: URL) -> String {
        url.deletingPathExtension().path.lowercased()
    }

    static let imageExtensions = ["heic", "HEIC", "jpg", "JPG", "jpeg", "JPEG", "png", "PNG"]
    static let videoExtensions = ["mov", "MOV", "mp4", "MP4"]

    static func siblingImage(of url: URL) -> URL? { sibling(of: url, extensions: imageExtensions) }
    static func siblingVideo(of url: URL) -> URL? { sibling(of: url, extensions: videoExtensions) }

    private static func sibling(of url: URL, extensions: [String]) -> URL? {
        let stem = url.deletingPathExtension()
        for ext in extensions where ext != url.pathExtension {
            let candidate = stem.appendingPathExtension(ext)
            if FileManager.default.fileExists(atPath: candidate.path) { return candidate }
        }
        return nil
    }
}

extension FileMarkers {
    static func unmarkProcessed(_ url: URL) { ExtendedAttributes.remove(processed, at: url) }
}
